//! End-to-end integration test for the hermetic local server.
//!
//! Builds a `TempDir` workspace, ingests an inline `Cargo.lock` through the
//! public `prism-api`, starts the server on an ephemeral port (port 0 -> read
//! the bound addr), connects with a raw `TcpStream`, and asserts the JSON
//! responses. Loopback only, self-cleaning temp dir, and fast; the
//! server thread is shut down at the end.

use std::io::{Read, Write};
use std::net::TcpStream;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use prism_api::{Ecosystem, Prism};
use prism_server::Server;

const CARGO_LOCK: &str = r#"
# @generated by Cargo
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "serde 1.0.197",
 "rand 0.8.5",
]

[[package]]
name = "serde"
version = "1.0.197"
source = "registry+https://github.com/rust-lang/crates.io-index"
dependencies = [
 "serde_derive 1.0.197",
]

[[package]]
name = "serde_derive"
version = "1.0.197"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "rand"
version = "0.8.5"
source = "registry+https://github.com/rust-lang/crates.io-index"
"#;

static COUNTER: AtomicU64 = AtomicU64::new(0);

/// A self-cleaning temp directory (no external crates).
struct TempDir {
    path: PathBuf,
}

impl TempDir {
    fn new(label: &str) -> Self {
        let n = COUNTER.fetch_add(1, Ordering::Relaxed);
        let pid = std::process::id();
        let path = std::env::temp_dir().join(format!("prism-server-it-{label}-{pid}-{n}"));
        std::fs::create_dir_all(&path).expect("create temp dir");
        Self { path }
    }
    fn path(&self) -> &Path {
        &self.path
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

/// One request/response roundtrip over a fresh connection; returns full text.
fn roundtrip(addr: std::net::SocketAddr, raw: &str) -> String {
    let mut stream = TcpStream::connect(addr).expect("connect to server");
    stream.write_all(raw.as_bytes()).expect("write request");
    let mut resp = String::new();
    stream.read_to_string(&mut resp).expect("read response");
    resp
}

/// Split an HTTP response text into (status_line, body).
fn split(resp: &str) -> (&str, &str) {
    let status = resp.lines().next().unwrap_or("");
    let body = resp.split("\r\n\r\n").nth(1).unwrap_or("");
    (status, body)
}

/// Pull the first run of decimal digits that immediately follows `needle`
/// (e.g. the `"pair":` value) out of a compact JSON body. No serde needed.
fn extract_u64_after(body: &str, needle: &str) -> Option<u64> {
    let start = body.find(needle)? + needle.len();
    let digits: String = body[start..].chars().take_while(|c| c.is_ascii_digit()).collect();
    digits.parse().ok()
}

#[test]
fn serve_workspace_end_to_end() {
    // (a) Build a temp workspace and ingest an inline Cargo.lock via prism_api.
    let tmp = TempDir::new("e2e");
    let run = {
        let mut prism = Prism::init(tmp.path()).expect("init workspace");
        let ingest = prism
            .ingest_lockfile_bytes(Ecosystem::Cargo, CARGO_LOCK.as_bytes())
            .expect("ingest lockfile");
        // Compute a TDA result so /api/tda has something to serve.
        prism.tda_run(ingest.run, "depth").expect("tda run");
        ingest.run
    };

    // (b) Re-open the workspace and start the server on an ephemeral port,
    // running on its own background threads (Server::start spawns them).
    let prism = Prism::open(tmp.path()).expect("reopen workspace");
    let mut server = Server::start(prism, 0, 2).expect("start server");
    let addr = server.addr();
    assert_eq!(addr.ip().to_string(), "127.0.0.1", "must bind loopback only");
    assert_ne!(addr.port(), 0, "an ephemeral port must have been chosen");

    // GET / returns the JSON service descriptor (UI is the separate web app).
    let home = roundtrip(addr, "GET / HTTP/1.1\r\nHost: localhost\r\n\r\n");
    let (status, body) = split(&home);
    assert!(status.starts_with("HTTP/1.1 200"), "home status: {status}");
    assert!(body.contains(r#""name":"prism-serve""#), "home body: {body}");
    assert!(body.contains("/api/export?run="), "home should list endpoints: {body}");
    // CORS is open so the Next.js app (a different origin) can call the API.
    assert!(home.contains("Access-Control-Allow-Origin: *"), "home headers: {home}");

    // (c) GET /api/graph/stats?run=<id> returns the right node/edge counts.
    let req = format!(
        "GET /api/graph/stats?run={} HTTP/1.1\r\nHost: localhost\r\n\r\n",
        run.get()
    );
    let stats = roundtrip(addr, &req);
    let (status, body) = split(&stats);
    assert!(status.starts_with("HTTP/1.1 200"), "stats status: {status}");
    assert!(body.contains(r#""nodes":4"#), "expected 4 nodes in: {body}");
    assert!(body.contains(r#""edges":3"#), "expected 3 edges in: {body}");
    assert!(body.contains(r#""has_cycle":false"#), "no cycle expected: {body}");

    // /api/status lists the run.
    let st = roundtrip(addr, "GET /api/status HTTP/1.1\r\nHost: localhost\r\n\r\n");
    let (status, body) = split(&st);
    assert!(status.starts_with("HTTP/1.1 200"), "status status: {status}");
    assert!(body.contains(r#""run_count":1"#), "status body: {body}");

    // /api/runs lists the run with its counts.
    let runs = roundtrip(addr, "GET /api/runs HTTP/1.1\r\nHost: localhost\r\n\r\n");
    let (_, body) = split(&runs);
    assert!(body.contains(r#""nodes":4"#), "runs body: {body}");

    // /api/export returns nodes and edges arrays for the UI.
    let req = format!(
        "GET /api/export?run={} HTTP/1.1\r\nHost: localhost\r\n\r\n",
        run.get()
    );
    let export = roundtrip(addr, &req);
    let (_, body) = split(&export);
    assert!(body.contains("graph_nodes"), "export body: {body}");
    assert!(body.contains("graph_edges"), "export body: {body}");

    // /api/graph/neighborhood of the root node 0 -> 3 forward-reachable nodes.
    let req = format!(
        "GET /api/graph/neighborhood?run={}&node=0&depth=8 HTTP/1.1\r\nHost: localhost\r\n\r\n",
        run.get()
    );
    let nb = roundtrip(addr, &req);
    let (status, body) = split(&nb);
    assert!(status.starts_with("HTTP/1.1 200"), "nb status: {status}");
    assert!(body.contains(r#""truncated":false"#), "nb body: {body}");

    // /api/tda returns a barcode with one connected component.
    let req = format!(
        "GET /api/tda?run={} HTTP/1.1\r\nHost: localhost\r\n\r\n",
        run.get()
    );
    let tda = roundtrip(addr, &req);
    let (status, body) = split(&tda);
    assert!(status.starts_with("HTTP/1.1 200"), "tda status: {status}");
    assert!(body.contains(r#""component_count":1"#), "tda body: {body}");

    // /api/tda/pairs lists individual persistence bars with birth/death/essential.
    let req = format!(
        "GET /api/tda/pairs?run={} HTTP/1.1\r\nHost: localhost\r\n\r\n",
        run.get()
    );
    let pairs = roundtrip(addr, &req);
    let (status, body) = split(&pairs);
    assert!(status.starts_with("HTTP/1.1 200"), "pairs status: {status}");
    assert!(body.contains(r#""dim":0"#), "pairs body: {body}");
    assert!(body.contains(r#""essential":true"#), "expected an essential H0 class: {body}");

    // /api/tda/support resolves a pair's generators to concrete graph objects.
    let pair_id = extract_u64_after(body, r#""pair":"#).expect("a pair id in the list");
    let req = format!(
        "GET /api/tda/support?run={}&pair={pair_id} HTTP/1.1\r\nHost: localhost\r\n\r\n",
        run.get()
    );
    let support = roundtrip(addr, &req);
    let (status, body) = split(&support);
    assert!(status.starts_with("HTTP/1.1 200"), "support status: {status}");
    assert!(body.contains(r#""objects":"#), "support body: {body}");
    assert!(body.contains(r#""type":"node""#), "an H0 generator is a node: {body}");

    // A missing pair param is a 400; an unknown pair is a 404.
    let req = format!(
        "GET /api/tda/support?run={} HTTP/1.1\r\nHost: localhost\r\n\r\n",
        run.get()
    );
    let resp = roundtrip(addr, &req);
    let (status, _) = split(&resp);
    assert!(status.starts_with("HTTP/1.1 400"), "missing pair status: {status}");
    let req = format!(
        "GET /api/tda/support?run={}&pair=999999999 HTTP/1.1\r\nHost: localhost\r\n\r\n",
        run.get()
    );
    let resp = roundtrip(addr, &req);
    let (status, _) = split(&resp);
    assert!(status.starts_with("HTTP/1.1 404"), "unknown pair status: {status}");

    // /api/package/candidates resolves a base purl to its version headroom. serde
    // appears at one version in the fixture (the purl is percent-encoded).
    let cand = roundtrip(
        addr,
        "GET /api/package/candidates?package=pkg%3Acargo%2Fserde HTTP/1.1\r\nHost: localhost\r\n\r\n",
    );
    let (status, body) = split(&cand);
    assert!(status.starts_with("HTTP/1.1 200"), "candidates status: {status}");
    assert!(body.contains(r#""package_purl":"pkg:cargo/serde""#), "candidates body: {body}");
    assert!(body.contains(r#""total_versions":1"#), "candidates body: {body}");
    assert!(body.contains(r#""ordinal":0"#), "candidates body: {body}");

    // A missing package param is a 400; an unknown package is a 404.
    let resp = roundtrip(addr, "GET /api/package/candidates HTTP/1.1\r\nHost: localhost\r\n\r\n");
    assert!(split(&resp).0.starts_with("HTTP/1.1 400"), "missing package: {resp}");
    let resp = roundtrip(
        addr,
        "GET /api/package/candidates?package=pkg%3Acargo%2Fnope HTTP/1.1\r\nHost: localhost\r\n\r\n",
    );
    assert!(split(&resp).0.starts_with("HTTP/1.1 404"), "unknown package: {resp}");

    // A missing run param is a 400 JSON error.
    let bad = roundtrip(addr, "GET /api/graph/stats HTTP/1.1\r\nHost: localhost\r\n\r\n");
    let (status, body) = split(&bad);
    assert!(status.starts_with("HTTP/1.1 400"), "bad status: {status}");
    assert!(body.contains("error"), "bad body: {body}");

    // An unknown run id is a 404 JSON error (NotFound from the store).
    let unknown = roundtrip(
        addr,
        "GET /api/graph/stats?run=999999 HTTP/1.1\r\nHost: localhost\r\n\r\n",
    );
    let (status, _) = split(&unknown);
    assert!(status.starts_with("HTTP/1.1 404"), "unknown run status: {status}");

    // (d) Shut the server thread down at the end.
    server.shutdown();
}
