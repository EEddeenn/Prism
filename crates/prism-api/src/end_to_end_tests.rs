#[test]
fn read_only_open_rejects_all_mutations() {
    // A read-only facade must refuse every mutating entry point at the boundary,
    // BEFORE any blob/disk side effect — not silently write attacker-controlled
    // content into the workspace.
    let td = TempDir::new("e2e-readonly");
    let lock = td.path().join("Cargo.lock");
    std::fs::write(&lock, CARGO_LOCK).unwrap();
    let run = {
        let mut prism = Prism::init(td.path()).unwrap();
        prism.ingest_lockfile(&lock).unwrap()
    };

    let mut ro = Prism::open_readonly(td.path()).unwrap();
    assert!(ro.is_read_only());
    // Reads still work.
    assert_eq!(ro.graph_stats(run).unwrap().nodes, 4);
    // Every mutation is rejected.
    assert!(ro.ingest_lockfile(&lock).is_err());
    assert!(ro
        .ingest_lockfile_bytes(Ecosystem::Cargo, CARGO_LOCK.as_bytes())
        .is_err());
    assert!(ro.tda_run(run, "depth").is_err());
    let man = td.path().join("Cargo.toml");
    std::fs::write(&man, "[package]\nname=\"x\"\nversion=\"0.1.0\"\n").unwrap();
    assert!(ro.resolve_manifest(&man, "highest").is_err());
}

#[test]
fn npm_lockfile_ingests_too() {
    let td = TempDir::new("e2e-npm");
    let lock = td.path().join("package-lock.json");
    std::fs::write(
        &lock,
        r#"{
          "lockfileVersion": 3,
          "packages": {
            "": { "version": "1.0.0", "dependencies": { "left-pad": "^1.3.0" } },
            "node_modules/left-pad": { "version": "1.3.0" }
          }
        }"#,
    )
    .unwrap();

    let mut prism = Prism::init(td.path()).unwrap();
    let run = prism.ingest_lockfile(&lock).unwrap();
    let stats = prism.graph_stats(run).unwrap();
    assert_eq!(stats.nodes, 2, "root + left-pad");
    assert_eq!(stats.edges, 1, "root -> left-pad");
    // A barcode still computes (two-node connected graph -> one component).
    let barcode = prism.tda_run(run, "depth").unwrap();
    assert_eq!(barcode.component_count(), 1);
}

#[test]
fn duplicate_version_family_is_detected() {
    // A lockfile with two coexisting serde versions is the classic "duplicate
    // dependency" situation: one family (serde) at two distinct versions.
    let td = TempDir::new("e2e-dups");
    let lock = td.path().join("Cargo.lock");
    std::fs::write(&lock, TWO_SERDE_LOCK).unwrap();
    let mut prism = Prism::init(td.path()).unwrap();
    let run = prism.ingest_lockfile(&lock).unwrap();

    // The headline stat counts *families* at >1 version, not versions.
    let stats = prism.graph_stats(run).unwrap();
    assert_eq!(
        stats.duplicate_version_count, 1,
        "serde present at two versions => one duplicate family"
    );

    // The detail report names the family and lists both versions.
    let clusters = prism.duplicate_clusters(run).unwrap();
    assert_eq!(clusters.len(), 1);
    let c = &clusters[0];
    assert!(c.package_purl.starts_with("pkg:cargo/serde"), "{}", c.package_purl);
    assert_eq!(c.versions.len(), 2, "serde 1.0.0 and 2.0.0");
    let purls: Vec<&str> = c.versions.iter().map(|v| v.purl.as_str()).collect();
    assert!(purls.iter().any(|p| p.contains("@1.0.0")), "{purls:?}");
    assert!(purls.iter().any(|p| p.contains("@2.0.0")), "{purls:?}");
}

/// A Cargo.lock with **two** versions of `serde` (1.0.0 and 2.0.0) so the package
/// family has a non-trivial candidate space for the analysis below.
const TWO_SERDE_LOCK: &str = r#"
# @generated by Cargo
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "serde 1.0.0",
]

[[package]]
name = "serde"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "serde"
version = "2.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
"#;

/// Find the `PackageId` of `serde` via a run node whose purl names it.
fn serde_package(prism: &Prism, run: prism_model::RunId) -> prism_model::PackageId {
    let stats = prism.graph_stats(run).unwrap();
    for i in 0..stats.nodes as u32 {
        let v = prism.node(run, GraphNodeId::new(i)).unwrap();
        if v.purl.starts_with("pkg:cargo/serde@") {
            return v.package.expect("serde node has a package");
        }
    }
    panic!("no serde node in run");
}

#[test]
fn candidates_conflict_and_synthetic_resolve_end_to_end() {
    let td = TempDir::new("e2e-candidates");
    let mut prism = Prism::init(td.path()).unwrap();

    // 1) Populate two serde versions (1.0.0, 2.0.0) via a lockfile.
    let lock = td.path().join("Cargo.lock");
    std::fs::write(&lock, TWO_SERDE_LOCK).unwrap();
    let lock_run = prism.ingest_lockfile(&lock).unwrap();
    let serde = serde_package(&prism, lock_run);

    // serde has exactly two versions in the snapshot.
    assert_eq!(prism.store().versions_by_package(serde).len(), 2);

    // 2) candidates_for: `^1` matches only 1.0.0 (ordinal 0); `^2` only 2.0.0.
    let c1 = prism
        .candidates_for(serde, "^1", Ecosystem::Cargo)
        .unwrap();
    assert_eq!(c1.total_versions, 2);
    assert_eq!(c1.count(), 1, "only serde 1.0.0 satisfies ^1");
    assert_eq!(c1.ranges, vec![0..1]);
    assert!(c1.candidates[0].purl.starts_with("pkg:cargo/serde@1.0.0"));
    assert_eq!(c1.reason, prism_model::CandidateReason::Constraint);

    let c2 = prism
        .candidates_for(serde, "^2", Ecosystem::Cargo)
        .unwrap();
    assert_eq!(c2.count(), 1, "only serde 2.0.0 satisfies ^2");
    assert_eq!(c2.ranges, vec![1..2]);

    // A `*` constraint admits both versions.
    let cstar = prism.candidates_for(serde, "*", Ecosystem::Cargo).unwrap();
    assert_eq!(cstar.count(), 2);

    // An unsatisfiable constraint yields an empty, Unsatisfiable view.
    let cnone = prism
        .candidates_for(serde, ">=9", Ecosystem::Cargo)
        .unwrap();
    assert!(cnone.is_empty());
    assert_eq!(cnone.reason, prism_model::CandidateReason::Unsatisfiable);

    // 3) Two manifests declaring conflicting requirements on serde.
    let man_a = td.path().join("Cargo.toml");
    std::fs::write(
        &man_a,
        "[package]\nname = \"app-a\"\nversion = \"1.0.0\"\n\n[dependencies]\nserde = \"^1\"\n",
    )
    .unwrap();
    prism.ingest_manifest(&man_a).unwrap();

    // Reuse the manifest path (cwd-independent ingest_manifest_bytes) for app-b.
    let man_b_bytes =
        b"[package]\nname = \"app-b\"\nversion = \"1.0.0\"\n\n[dependencies]\nserde = \"^2\"\n";
    prism
        .ingest_manifest_bytes(Ecosystem::Cargo, man_b_bytes)
        .unwrap();

    // conflict_pressure: two requirements target serde, and ^1 vs ^2 are disjoint.
    let report = prism.conflict_pressure(serde, Ecosystem::Cargo).unwrap();
    assert_eq!(report.total_versions, 2);
    assert!(
        report.requirement_count() >= 2,
        "two requirements target serde: {:?}",
        report.set_sizes
    );
    assert!(report.has_conflict(), "^1 and ^2 cannot share a serde version");
    // Tightness is 0 here: between them ^1 and ^2 cover both versions (union=2/2).
    assert!((report.tightness - 0.0).abs() < 1e-9, "{}", report.tightness);

    // candidates(requirement_id): resolve a stored requirement's candidate space.
    let req_id = prism.store().requirements_by_dst_package(serde)[0];
    let view = prism.candidates(req_id).unwrap();
    assert_eq!(view.package, serde);
    assert_eq!(view.total_versions, 2);

    // 4) resolve_synthetic: ingest a fresh manifest + resolve to a run. We use a
    // separate workspace so the root is unambiguous.
    let td2 = TempDir::new("e2e-synthetic");
    let mut prism2 = Prism::init(td2.path()).unwrap();
    // Seed serde versions there too (the resolver selects from stored versions).
    std::fs::write(td2.path().join("Cargo.lock"), TWO_SERDE_LOCK).unwrap();
    prism2
        .ingest_lockfile(td2.path().join("Cargo.lock"))
        .unwrap();

    let man = td2.path().join("Cargo.toml");
    std::fs::write(
        &man,
        "[package]\nname = \"root\"\nversion = \"1.0.0\"\n\n[dependencies]\nserde = \"^2\"\n",
    )
    .unwrap();
    let res = prism2.resolve_manifest(&man, "highest").unwrap();
    // Sane stats: root + serde occurrence, one resolved edge between them.
    assert_eq!(res.nodes, 2, "root + serde");
    assert_eq!(res.edges, 1, "root -> serde");
    assert!(!res.truncated);
    // The selected serde is 2.0.0 (highest-non-prerelease satisfying ^2).
    let resolved_serde = (0..res.nodes as u32)
        .map(|i| prism2.node(res.run, GraphNodeId::new(i)).unwrap())
        .find(|n| n.purl.starts_with("pkg:cargo/serde@"))
        .expect("serde resolved into the graph");
    assert!(
        resolved_serde.purl.starts_with("pkg:cargo/serde@2.0.0"),
        "{}",
        resolved_serde.purl
    );
    let stats = prism2.graph_stats(res.run).unwrap();
    assert_eq!(stats.nodes, res.nodes);
    assert_eq!(stats.edges, res.edges);
    // The run is recorded as ModelResolved.
    let run_rec = prism2.store().get_run(res.run).unwrap();
    assert_eq!(run_rec.fidelity.tier, prism_model::FidelityTier::ModelResolved);

    // `lowest` policy is also accepted and produces a sane run.
    let res_low = prism2.resolve_manifest(&man, "lowest").unwrap();
    assert!(res_low.nodes >= 1);
    assert_ne!(res_low.run, res.run, "a fresh run id each time");

    // Idempotent re-ingest: resolving the SAME manifest again must not accumulate
    // duplicate requirements (and thus duplicate edges) — the graph size is
    // identical to the first `highest` run, only the run id differs.
    let res_again = prism2.resolve_manifest(&man, "highest").unwrap();
    assert_eq!(res_again.nodes, res.nodes, "re-resolve: same node count");
    assert_eq!(
        res_again.edges, res.edges,
        "re-resolve must not duplicate edges"
    );
    assert_ne!(res_again.run, res.run, "still a fresh run id");

    // An unknown policy is a clear error, not a panic.
    assert!(prism2.resolve_manifest(&man, "bogus").is_err());
}
