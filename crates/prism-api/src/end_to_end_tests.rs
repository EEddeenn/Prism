//! End-to-end vertical slice: a real `TempDir` workspace and an inline
//! `Cargo.lock` fixture driven through the whole facade.
//!
//! init → ingest_lockfile → graph_stats (asserts node/edge counts) → tda_run
//! (asserts a non-empty H0 barcode) → neighborhood/impact queries (assert the
//! expected nodes) → reopen and re-query. This is the must-have slice.

use crate::test_util::TempDir;
use crate::{Ecosystem, Prism};
use prism_model::GraphNodeId;

/// 4 crates: `app` (root) depends on `serde` and `rand`; `serde` depends on
/// `serde_derive`. One real dependency edge chain plus a fan-out.
const CARGO_LOCK: &str = r#"
# @generated by Cargo
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "serde 1.0.197",
 "rand 0.8.5",
]

[[package]]
name = "serde"
version = "1.0.197"
source = "registry+https://github.com/rust-lang/crates.io-index"
dependencies = [
 "serde_derive 1.0.197",
]

[[package]]
name = "serde_derive"
version = "1.0.197"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "rand"
version = "0.8.5"
source = "registry+https://github.com/rust-lang/crates.io-index"
"#;

fn write_lock(dir: &std::path::Path) -> std::path::PathBuf {
    let p = dir.join("Cargo.lock");
    std::fs::write(&p, CARGO_LOCK).unwrap();
    p
}

#[test]
fn lockfile_to_graph_to_tda_end_to_end() {
    let td = TempDir::new("e2e");
    let lock = write_lock(td.path());

    // init -> ingest_lockfile.
    let mut prism = Prism::init(td.path()).unwrap();
    assert_eq!(Prism::detect(&lock), Some(Ecosystem::Cargo));
    let run = prism.ingest_lockfile(&lock).unwrap();

    // graph_stats: 4 nodes; edges app->serde, app->rand, serde->serde_derive = 3.
    let stats = prism.graph_stats(run).unwrap();
    assert_eq!(stats.nodes, 4, "four crates -> four nodes");
    assert_eq!(stats.edges, 3, "three resolved dependency edges");
    assert!(!stats.has_cycle, "a Cargo.lock dependency tree has no cycle");
    assert_eq!(stats.scc_count, 4, "a DAG -> one component per node");
    assert_eq!(stats.duplicate_version_count, 0, "no duplicated versions");
    // Depth is BFS distance from the root member: app(0) -> serde(1) ->
    // serde_derive(2); app -> rand(1). So the deepest node is serde_derive at 2.
    assert_eq!(stats.max_depth, 2, "app -> serde -> serde_derive is depth 2");

    // tda_run: depth filtration -> non-empty barcode with one H0 component (the
    // tree is connected) and no H1 cycles.
    let barcode = prism.tda_run(run, "depth").unwrap();
    assert!(barcode.is_nonempty(), "the barcode must have bars");
    assert_eq!(
        barcode.component_count(),
        1,
        "the dependency tree is connected -> one H0 class"
    );
    assert_eq!(barcode.cycle_count(), 0, "a tree has no H1 cycles");

    // The persisted .ptda is discoverable for the run.
    let filtrations = prism.tda_filtrations(run);
    assert_eq!(filtrations.len(), 1);
    let reread = prism.tda_barcode(run, filtrations[0]).unwrap();
    assert_eq!(reread.component_count(), 1);

    // neighborhood of the root `app` (node 0): forward-reachable descendants are
    // serde, rand, serde_derive = 3 nodes.
    let root = GraphNodeId::new(0);
    let nbhd = prism.neighborhood(run, root, 10, 100).unwrap();
    assert_eq!(nbhd.nodes.len(), 3, "app reaches serde, rand, serde_derive");
    assert!(!nbhd.truncated);
    // The center is the root with depth 0.
    assert_eq!(nbhd.center.id, root);
    assert_eq!(nbhd.center.depth, 0);
    // Induced edges among {app, serde, rand, serde_derive} = all 3.
    assert_eq!(nbhd.edges.len(), 3);
    // The center's purl is a cargo purl for app.
    assert!(nbhd.center.purl.starts_with("pkg:cargo/app@"), "{}", nbhd.center.purl);

    // impact of `serde_derive`: ancestors that depend on it = serde, app.
    let sd_node = find_node_by_purl(&prism, run, "serde_derive");
    let impact = prism.impact(run, sd_node, 10).unwrap();
    let mut ancestor_purls: Vec<String> = impact.nodes.iter().map(|n| pkg_of(&n.purl)).collect();
    ancestor_purls.sort();
    assert_eq!(ancestor_purls, vec!["app", "serde"]);

    // duplicate_clusters: none in this graph.
    assert!(prism.duplicate_clusters(run).unwrap().is_empty());

    // scc: four singleton components.
    let sccs = prism.scc(run).unwrap();
    assert_eq!(sccs.len(), 4);
    assert!(sccs.iter().all(|c| c.len() == 1));

    // Reopen the workspace and re-query: persistence is durable.
    drop(prism);
    let prism2 = Prism::open(td.path()).unwrap();
    let stats2 = prism2.graph_stats(run).unwrap();
    assert_eq!(stats2.nodes, 4);
    assert_eq!(stats2.edges, 3);
    let barcode2 = prism2.tda_barcode(run, filtrations[0]).unwrap();
    assert_eq!(barcode2.component_count(), 1);
}

/// Find the snapshot-local node id whose resolved purl names `crate_name`.
fn find_node_by_purl(prism: &Prism, run: prism_model::RunId, crate_name: &str) -> GraphNodeId {
    let stats = prism.graph_stats(run).unwrap();
    for i in 0..stats.nodes as u32 {
        let view = prism.node(run, GraphNodeId::new(i)).unwrap();
        if pkg_of(&view.purl) == crate_name {
            return GraphNodeId::new(i);
        }
    }
    panic!("no node for {crate_name}");
}

/// Extract the crate name from a `pkg:cargo/<name>@<version>` purl.
fn pkg_of(purl: &str) -> String {
    purl.strip_prefix("pkg:cargo/")
        .and_then(|s| s.split('@').next())
        .unwrap_or(purl)
        .to_string()
}

#[test]
fn manifest_ingest_writes_records() {
    let td = TempDir::new("e2e-manifest");
    let manifest = td.path().join("Cargo.toml");
    std::fs::write(
        &manifest,
        r#"
        [package]
        name = "demo"
        version = "1.2.3"

        [dependencies]
        serde = "1.0"
        anyhow = "1"
    "#,
    )
    .unwrap();

    let mut prism = Prism::init(td.path()).unwrap();
    let out = prism.ingest_manifest(&manifest).unwrap();
    assert_eq!(out.ecosystem, Ecosystem::Cargo);
    // demo (package+version) plus serde/anyhow as targets, and 2 requirements.
    assert!(out.versions >= 1, "the declaring version is recorded");
    assert_eq!(out.requirements, 2, "two declared dependencies");
}

