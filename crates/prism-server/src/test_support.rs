//! Shared test fixtures: a self-cleaning temp workspace with one ingested
//! Cargo.lock, used by the server and integration tests. Not compiled into the
//! release binary.

use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

use prism_api::{Ecosystem, Prism};
use prism_model::RunId;

static COUNTER: AtomicU64 = AtomicU64::new(0);

/// A temporary directory removed on drop (no external crates).
pub struct TempDir {
    path: PathBuf,
}

impl TempDir {
    /// Create a uniquely-named temp directory tagged with `label`.
    pub fn new(label: &str) -> Self {
        let n = COUNTER.fetch_add(1, Ordering::Relaxed);
        let pid = std::process::id();
        let path = std::env::temp_dir().join(format!("prism-server-test-{label}-{pid}-{n}"));
        std::fs::create_dir_all(&path).expect("create temp dir");
        Self { path }
    }

    /// The directory path.
    pub fn path(&self) -> &Path {
        &self.path
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.path);
    }
}

/// The same 4-crate fixture the facade's end-to-end test uses: `app` -> serde,
/// rand; serde -> serde_derive. 4 nodes, 3 edges, no cycle.
pub const CARGO_LOCK: &str = r#"
# @generated by Cargo
version = 3

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "serde 1.0.197",
 "rand 0.8.5",
]

[[package]]
name = "serde"
version = "1.0.197"
source = "registry+https://github.com/rust-lang/crates.io-index"
dependencies = [
 "serde_derive 1.0.197",
]

[[package]]
name = "serde_derive"
version = "1.0.197"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "rand"
version = "0.8.5"
source = "registry+https://github.com/rust-lang/crates.io-index"
"#;

/// Build a temp workspace, ingest [`CARGO_LOCK`], and return the open facade,
/// the run id, and the live [`TempDir`] (keep it alive for the test's duration).
pub fn ingested_workspace() -> (TempDir, Prism, RunId) {
    let tmp = TempDir::new("ws");
    let mut prism = Prism::init(tmp.path()).expect("init workspace");
    let run = prism
        .ingest_lockfile_bytes(Ecosystem::Cargo, CARGO_LOCK.as_bytes())
        .expect("ingest lockfile")
        .run;
    (tmp, prism, run)
}
