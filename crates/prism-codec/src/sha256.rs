//! Pure-Rust SHA-256 (FIPS 180-4).
//!
//! Used for blob content-addressing and whole-file digests in the manifest.
//! Implemented in-crate to keep the foundation dependency-free; verified against
//! the standard test vectors.

use prism_model::HashDigest;

